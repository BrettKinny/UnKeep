#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import {
  existsSync,
  readFileSync,
  readdirSync,
  realpathSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const noticePath = join(repositoryRoot, 'THIRD_PARTY_NOTICES.md');
const checkOnly = process.argv.includes('--check');
const bundledWebPackages = [
  '@sveltejs/kit',
  'clsx',
  'devalue',
  'esm-env',
  'svelte',
  'tailwindcss',
  'vite',
  'zimmerframe',
];
const packages = new Map();

function fail(message) {
  throw new Error(message);
}

function readManifest(directory) {
  const path = join(directory, 'package.json');
  if (!existsSync(path)) fail(`Dependency is missing package.json: ${directory}`);
  return JSON.parse(readFileSync(path, 'utf8'));
}

function licenseFiles(directory) {
  return readdirSync(directory)
    .filter((name) => /^(?:licen[cs]e|copying|notice)(?:[._-].*)?$/i.test(name))
    .filter((name) => statSync(join(directory, name)).isFile())
    .sort((left, right) => left.localeCompare(right, 'en'));
}

function repositoryUrl(repository) {
  if (typeof repository === 'string') return repository;
  if (repository && typeof repository.url === 'string') return repository.url;
  return undefined;
}

function collectPackage(inputDirectory) {
  const directory = realpathSync(inputDirectory);
  const manifest = readManifest(directory);
  if (typeof manifest.name !== 'string' || typeof manifest.version !== 'string') {
    fail(`Dependency has incomplete identity metadata: ${directory}`);
  }

  const key = `${manifest.name}@${manifest.version}`;
  if (!packages.has(key)) {
    const files = licenseFiles(directory);
    if (!files.length) fail(`${key} has no top-level license or notice file`);
    packages.set(key, {
      name: manifest.name,
      version: manifest.version,
      license: typeof manifest.license === 'string' ? manifest.license : 'See included text',
      homepage: typeof manifest.homepage === 'string'
        ? manifest.homepage
        : repositoryUrl(manifest.repository),
      notices: files.map((name) => ({
        name,
        text: readFileSync(join(directory, name), 'utf8')
          .replace(/\r\n?/g, '\n')
          .replace(/[ \t]+$/gm, '')
          .trim(),
      })),
    });
  }

}

function licenseInventory(dependencyKind) {
  const result = spawnSync('pnpm', ['licenses', 'list', dependencyKind, '--json'], {
    cwd: repositoryRoot,
    encoding: 'utf8',
    env: { ...process.env, NO_UPDATE_NOTIFIER: '1' },
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    fail(`pnpm ${dependencyKind} license inventory failed:\n${result.stderr.trim()}`);
  }

  return Object.values(JSON.parse(result.stdout)).flat();
}

for (const entry of licenseInventory('--prod')) {
  for (const directory of entry.paths ?? []) collectPackage(directory);
}
const developmentInventory = licenseInventory('--dev');
for (const name of bundledWebPackages) {
  const entries = developmentInventory.filter((entry) => entry.name === name);
  if (!entries.length) fail(`Bundled web dependency is missing from pnpm's inventory: ${name}`);
  for (const entry of entries) {
    for (const directory of entry.paths ?? []) collectPackage(directory);
  }
}

const sections = [...packages.values()]
  .sort((left, right) => {
    const byName = left.name.localeCompare(right.name, 'en');
    return byName || left.version.localeCompare(right.version, 'en');
  })
  .map((dependency) => {
    const metadata = [
      `License: ${dependency.license}`,
      dependency.homepage ? `Project: ${dependency.homepage}` : null,
    ].filter(Boolean).join('\n');
    const texts = dependency.notices
      .map((notice) => `### ${notice.name}\n\n\`\`\`text\n${notice.text}\n\`\`\``)
      .join('\n\n');
    return `## ${dependency.name}@${dependency.version}\n\n${metadata}\n\n${texts}`;
  });

const generated = `# UnKeep third-party notices

This file is generated by \`pnpm notices\`; do not edit it manually.

It contains the license and notice files for UnKeep's installed production
dependency graph. It also includes the web framework and runtime packages whose
implementation or generated output is incorporated into the static application.

${sections.join('\n\n')}
`;

if (checkOnly) {
  if (!existsSync(noticePath) || readFileSync(noticePath, 'utf8') !== generated) {
    fail('THIRD_PARTY_NOTICES.md is stale; run `pnpm notices` and commit the result');
  }
  process.stdout.write(`Verified ${packages.size} third-party package notices.\n`);
} else {
  writeFileSync(noticePath, generated);
  process.stdout.write(`Wrote ${packages.size} third-party package notices to THIRD_PARTY_NOTICES.md.\n`);
}
